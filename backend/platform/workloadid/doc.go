// Package workloadid реализует идентичность рабочих нагрузок и авторизацию
// внутренних RPC по ADR-0004: mTLS подтверждает машинную идентичность
// (среда + роль), но сам по себе не даёт доступ к методам — пакет извлекает
// идентичность из сертификата пира и применяет политику «кто может вызвать
// что» к внутренним gRPC-вызовам.
//
// Идентичность кодируется SPIFFE-совместимым URI SAN вида
// spiffe://<trust-domain>/<env>/<role>[/<instance>]. Политика авторизации
// fail-closed: вызов без явного правила отклоняется. Отзыв отдельной
// идентичности выполняется по серийному номеру сертификата без замены
// сертификатов остальных рабочих нагрузок.
//
// Осознанное ограничение: пакет использует только стандартную библиотеку
// и google.golang.org/grpc, не добавляя новых зависимостей в go.mod.
